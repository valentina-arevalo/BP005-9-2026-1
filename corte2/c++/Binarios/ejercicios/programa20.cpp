#include <iostream>
#include <cmath>

using namespace std;

int main() {
    cout << "sqrt(16) = "
         << sqrt(16) << endl;

    cout << "pow(2,3) = "
         << pow(2,3) << endl;

    cout << "fabs(-3.5) = "
         << fabs(-3.5) << endl;

    cout << "round(3.6) = "
         << round(3.6) << endl;

    cout << "floor(3.9) = "
         << floor(3.9) << endl;

    cout << "ceil(3.1) = "
         << ceil(3.1) << endl;

    return 0;
}
